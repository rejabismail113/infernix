<?php

declare(strict_types=1);

namespace App\Console\Commands;

use App\Kernel\Identity\Http\Middleware\EnsureMfa;
use App\Kernel\Identity\Http\Middleware\RequireRecentAuth;
use App\Kernel\Identity\Models\User;
use Illuminate\Auth\SessionGuard;
use Illuminate\Console\Command;
use Illuminate\Contracts\Http\Kernel as HttpKernel;
use Illuminate\Http\Request;
use Illuminate\Support\Facades\DB;

/**
 * NFR-05 benchmark: inside ONE transaction that is always rolled back (no data is left behind), seed a
 * large dataset (default 50k rows per hot table), then time common list / detail pages through the real HTTP
 * kernel as the Owner (all middleware, policies and Inertia rendering) and report p50 / p95. Fails when any
 * p95 exceeds the 3 s target. `--write` stores the result table in docs/PERFORMANCE.md.
 *
 * @see SRS NFR-05
 */
final class PerfBenchmark extends Command
{
    protected $signature = 'perf:benchmark {--rows=50000} {--iterations=15} {--write}';

    protected $description = 'Seed a large dataset in a rolled-back transaction and measure p95 of common pages (NFR-05).';

    public function handle(): int
    {
        $rows = max(1000, (int) $this->option('rows'));
        $iterations = max(3, (int) $this->option('iterations'));
        $owner = User::query()->whereHas('roles', fn ($r) => $r->where('code', 'OWN'))->orderBy('id')->firstOrFail();
        DB::beginTransaction();
        try {
            $t0 = microtime(true);
            $this->seed($rows, $owner);
            $this->info(sprintf('Seeded %d rows per table in %.1f s (rolled back afterwards).', $rows, microtime(true) - $t0));
            DB::statement('ANALYZE');
            $session = app('session')->driver();
            $session->put(['login_web_'.sha1(SessionGuard::class) => $owner->id, EnsureMfa::SESSION_KEY => now()->toIso8601String(),
                RequireRecentAuth::SESSION_KEY => now()->toIso8601String(), RequireRecentAuth::MFA_SESSION_KEY => now()->toIso8601String()]);
            $firstTxn = (int) DB::table('transactions')->max('id');
            $pages = [
                'Expenses & income (list)' => '/finance/transactions', 'Expense detail' => "/finance/transactions/{$firstTxn}", 'Claims (list)' => '/finance/claims',
                'Bills (list)' => '/finance/bills', 'Audit log (list)' => '/admin/audit-log', 'Trial balance' => '/finance/reports/trial-balance',
                'Owner dashboard' => '/reports/dashboard/owner', 'Project dashboard' => '/reports/projects', 'Global search' => '/search?q=bench',
            ];
            $results = [];
            foreach ($pages as $label => $url) {
                $times = [];
                $status = 0;
                for ($i = 0; $i < $iterations; $i++) {
                    $req = Request::create($url, 'GET', [], [], [], ['HTTP_ACCEPT' => 'text/html, application/xhtml+xml']);
                    $s = hrtime(true);
                    $res = app(HttpKernel::class)->handle($req);
                    $times[] = (hrtime(true) - $s) / 1e6;
                    $status = $res->getStatusCode();
                }
                sort($times);
                $p = fn (float $q): float => $times[(int) min(count($times) - 1, ceil($q * count($times)) - 1)];
                $results[] = [$label, $url, $status, round($p(0.5)), round($p(0.95))];
            }
        } finally {
            DB::rollBack();
        }
        $this->table(['Page', 'URL', 'HTTP', 'p50 ms', 'p95 ms'], $results);
        $slow = array_filter($results, fn (array $r): bool => $r[4] > 3000 || $r[2] >= 400);
        if ($this->option('write')) {
            $md = "# Performance benchmark (NFR-05)\n\nGenerated by `php artisan perf:benchmark --rows={$rows} --iterations={$iterations} --write` on ".now()->toDateTimeString().".\n"
                ."Dataset: {$rows} rows each in audit_events, transactions (+lines), claims, bills (+lines) and posted journals, seeded inside a transaction that is rolled back.\n"
                ."Requests go through the full HTTP kernel (auth, policies, Inertia) as the Owner, single process, no HTTP server overhead. Target: p95 < 3000 ms.\n\n"
                ."| Page | URL | HTTP | p50 ms | p95 ms |\n|---|---|---|---|---|\n";
            foreach ($results as $r) {
                $md .= "| {$r[0]} | `{$r[1]}` | {$r[2]} | {$r[3]} | {$r[4]} |\n";
            }
            $md .= "\nFor load under concurrency use `scripts/k6/smoke.js` against staging (see docs/DEPLOYMENT.md).\n";
            file_put_contents(base_path('docs/PERFORMANCE.md'), $md);
        }
        if ($slow !== []) {
            $this->error('Some pages miss the p95 < 3 s target or failed.');

            return self::FAILURE;
        }
        $this->info('All pages within the p95 < 3 s target.');

        return self::SUCCESS;
    }

    private function seed(int $n, User $owner): void
    {
        $company = (int) $owner->company_id;
        $u = $owner->id;
        $bank = (int) DB::table('bank_accounts')->value('id');
        $vendor = (int) DB::table('vendors')->insertGetId(['company_id' => $company, 'name' => 'Bench vendor', 'status' => 'active', 'created_at' => now(), 'updated_at' => now()]);
        $expense = (int) DB::table('chart_accounts')->where('code', '5040')->value('id');
        $bankGl = (int) DB::table('bank_accounts')->where('id', $bank)->value('gl_account_id');
        $date = now()->toDateString();
        DB::statement("INSERT INTO audit_events (company_id, actor_id, actor_role, action, entity_type, entity_id, request_id, occurred_at)
            SELECT {$company}, {$u}, 'OWN', 'bench', 'bench', g, md5(g::text)::uuid, now() - (g || ' seconds')::interval FROM generate_series(1, {$n}) g");
        DB::statement("INSERT INTO transactions (company_id, transaction_no, direction, payment_source, capitalization_class, transaction_date, gross_amount, bank_account_id, description, status, tax_treatment, created_by, created_at, updated_at)
            SELECT {$company}, 'BENCH-' || g, 'outflow', 'DIRECT_COMPANY', 'EXPENSE', DATE '{$date}' - (g % 300), 10 + (g % 500), {$bank}, 'bench expense ' || g, 'draft', 'pending_review', {$u}, now(), now() FROM generate_series(1, {$n}) g");
        DB::statement("INSERT INTO transaction_lines (transaction_id, line_no, description, amount) SELECT id, 1, 'bench line', gross_amount FROM transactions WHERE transaction_no LIKE 'BENCH-%'");
        DB::statement("INSERT INTO claims (company_id, claim_no, staff_user_id, purpose, status, total_amount, created_by, created_at, updated_at)
            SELECT {$company}, 'BENCH-CL-' || g, {$u}, 'bench claim ' || g, 'draft', 25, {$u}, now() - (g || ' minutes')::interval, now() FROM generate_series(1, {$n}) g");
        DB::statement("INSERT INTO bills (company_id, bill_no, vendor_id, vendor_invoice_no, bill_date, due_date, total_amount, status, created_by, created_at, updated_at)
            SELECT {$company}, 'BENCH-BL-' || g, {$vendor}, 'BINV-' || g, DATE '{$date}' - (g % 300), DATE '{$date}', 99, 'draft', {$u}, now(), now() FROM generate_series(1, {$n}) g");
        $period = DB::table('fiscal_periods')->where('starts_on', '<=', $date)->where('ends_on', '>=', $date)->first();
        if ($period !== null && $period->locked_at === null) {
            $jn = intdiv($n, 5);
            DB::statement("INSERT INTO journals (company_id, journal_no, journal_date, posting_date, fiscal_period_id, source_type, memo, status, created_by, created_at, updated_at)
                SELECT {$company}, 'BENCH-JV-' || g, DATE '{$date}', DATE '{$date}', {$period->id}, 'manual', 'bench', 'draft', {$u}, now(), now() FROM generate_series(1, {$jn}) g");
            DB::statement("INSERT INTO journal_lines (journal_id, line_no, account_id, debit, credit) SELECT id, 1, {$expense}, 10, 0 FROM journals WHERE journal_no LIKE 'BENCH-JV-%'");
            DB::statement("INSERT INTO journal_lines (journal_id, line_no, account_id, debit, credit) SELECT id, 2, {$bankGl}, 0, 10 FROM journals WHERE journal_no LIKE 'BENCH-JV-%'");
            DB::statement("UPDATE journals SET status = 'posted', posted_at = now(), posted_by = {$u} WHERE journal_no LIKE 'BENCH-JV-%'");
        }
        DB::statement("INSERT INTO search_index (entity_type, entity_id, title, body, module, indexed_at) SELECT 'vendor', {$vendor} + g, 'bench item ' || g, null, 'Bench', now() FROM generate_series(1, {$n}) g ON CONFLICT DO NOTHING");
    }
}
